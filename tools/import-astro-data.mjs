// Generates source/game_astro_data.h from the shared Astro data (public/data/astro.json).
// Usage: GOPENGUIN_WEB=/path/to/gopenguin/web node tools/import-astro-data.mjs
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';

const root=path.dirname(import.meta.dirname);
const web=process.env.GOPENGUIN_WEB??path.resolve(root,'../../gopenguin-dev/web');
const data=JSON.parse(await readFile(path.join(web,'public/data/astro.json'),'utf8'));
const kinds={barrier:'ASTRO_BARRIER',yellow:'ASTRO_YELLOW',slide:'ASTRO_SLIDE',block:'ASTRO_BLOCK',orange:'ASTRO_ORANGE',switch:'ASTRO_SWITCH',turret:'ASTRO_TURRET',oneup:'ASTRO_ONEUP',train:'ASTRO_TRAIN',bonus:'ASTRO_BONUS'};
const normal=data.levels.filter(level=>!level.secret);
if(data.levels.length!==60||normal.length!==40)throw new Error('Unexpected Astro level count');
const num=value=>Number.isInteger(value)?String(value):String(value);
const box=b=>`{${b.map(num).join(',')}}`;
const clipIds=Object.keys(data.clips),wallIds=Object.keys(data.walls);
const clipIndex=id=>{const i=clipIds.indexOf(String(id));if(i<0)throw new Error('clip '+id);return i;};
const wallIndex=id=>{const i=wallIds.indexOf(String(id));if(i<0)throw new Error('wall '+id);return i;};

let out=`// Generated by tools/import-astro-data.mjs from public/data/astro.json.
// Source: ${data.source.path} ${data.source.sha256 ?? data.source.id}
#pragma once
#include <stdbool.h>

typedef enum {
 ASTRO_BARRIER,ASTRO_YELLOW,ASTRO_SLIDE,ASTRO_BLOCK,ASTRO_ORANGE,
 ASTRO_SWITCH,ASTRO_TURRET,ASTRO_ONEUP,ASTRO_TRAIN,ASTRO_BONUS
} AstroKind;

/** One frame of a target clip: which wall sprite and the wall's matrix inside the clip. */
typedef struct {unsigned short wall;double m[6];} AstroClipFrame;
typedef struct {bool loop;unsigned frames,first;} AstroClipData;
typedef struct {unsigned frames,first;unsigned char stops[4];unsigned stopCount;} AstroWallData;
typedef struct {const char *name;int clip;double matrix[6];unsigned start;} AstroPartData;
typedef struct {const char *name;AstroKind kind;double box[4];double matrix[6];int clip;unsigned dir,partFirst,partCount;int turretFirst;unsigned tracking;double gunFrames[3];unsigned start;} AstroObjectData;
typedef struct {const char *name;unsigned frame;bool secret;unsigned shots,hits,first,count;bool unlimitedShots;unsigned finalHits;} AstroLevelData;
typedef struct {const char *name;unsigned frame,level,first,count;bool hasPlane;double plane[4];unsigned secretSet;int turret;} AstroIntroData;

`;
const frames=[],clips=[];
for(const id of clipIds){const c=data.clips[id];clips.push(` {${c.loop?'true':'false'},${c.wall.length},${frames.length}},`);for(const f of c.wall)frames.push(` {${wallIndex(f[0])},{${f.slice(1).map(num).join(',')}}},`);}
const wallBoxes=[],walls=[];
for(const id of wallIds){const w=data.walls[id];const stops=w.stops.slice(0,4);walls.push(` {${w.boxes.length},${wallBoxes.length},{${[...stops,0,0,0,0].slice(0,4).join(',')}},${stops.length}},`);for(const b of w.boxes)wallBoxes.push(` ${box(b)},`);}
const objects=[],parts=[],turretBoxes=[];
const object=o=>{
  if(!kinds[o.kind])throw new Error('Unknown kind '+o.kind);
  let partFirst=0,partCount=0,turretFirst=-1;
  if(o.parts){partFirst=parts.length;partCount=o.parts.length;for(const p of o.parts)parts.push(` {"${p.name}",${clipIndex(p.clip)},{${p.matrix.map(num).join(',')}},${p.start}},`);}
  if(o.kind==='turret'&&Array.isArray(o.frames)){turretFirst=turretBoxes.length;for(const b of o.frames)turretBoxes.push(` ${box(b)},`);}
  const m=o.matrix??[1,0,0,1,0,0];
  objects.push(` {"${o.name}",${kinds[o.kind]},${box(o.box)},{${m.map(num).join(',')}},${o.clip?clipIndex(o.clip):-1},${o.dir??0},${partFirst},${partCount},${turretFirst},${({'gun-y':1,'gun-x':2,orbit:3})[o.tracking]??0},{${(o.gunFrames??[0,0,0]).map(num).join(',')}},${o.start??1}},`);
};
const levels=[];
for(const level of data.levels){const first=objects.length;level.objects.forEach(object);levels.push(` {"${level.name}",${level.frame},${level.secret?'true':'false'},${level.shots},${level.hits},${first},${level.objects.length},${level.unlimitedShots?'true':'false'},${level.finalHits??0}},`);}
const intros=[];
for(const intro of data.intros){
  const first=objects.length;intro.objects.forEach(object);
  let turret=-1;if(intro.turret){turret=objects.length;object({name:'turret',kind:'turret',box:intro.turret.frames[0],matrix:intro.turret.matrix,dir:intro.turret.dir,frames:intro.turret.frames});}
  intros.push(` {"${intro.name}",${intro.frame},${intro.level},${first},${intro.objects.length},${intro.plane?'true':'false'},${box(intro.plane??[0,0,0,0])},${intro.secretSet??0},${turret}},`);
}
const maxObjects=Math.max(...data.levels.map(level=>level.objects.length),...data.intros.map(intro=>intro.objects.length+(intro.turret?1:0)));
const maxParts=Math.max(...data.levels.flatMap(level=>level.objects.map(o=>o.parts?.length??0)));
const p=data.projectiles,o=data.overlays;
out+=`#define ASTRO_LEVELS ${data.levels.length}
#define ASTRO_NORMAL_LEVELS ${normal.length}
#define ASTRO_INTROS ${intros.length}
#define ASTRO_OBJECTS ${objects.length}
#define ASTRO_MAX_OBJECTS ${maxObjects}
#define ASTRO_MAX_PARTS ${maxParts}
#define ASTRO_OVERLAY_DONE ${o.leveldone}
#define ASTRO_OVERLAY_RESTART ${o.levelrestart}
#define ASTRO_PROMPT_READY ${o.promptReady}
#define ASTRO_PLANE_DELAY ${o.planeDelay}

static const double ASTRO_GUN_BOX[4]=${box(p.gun)},ASTRO_BULLET_BOX[4]=${box(p.bullet)},ASTRO_TURRET_BULLET_BOX[4]=${box(p.turretbullet)};
static const AstroClipFrame ASTRO_CLIP_FRAMES[${frames.length}]={
${frames.join('\n')}
};
static const AstroClipData ASTRO_CLIP_DATA[${clips.length}]={
${clips.join('\n')}
};
static const double ASTRO_WALL_BOXES[${wallBoxes.length}][4]={
${wallBoxes.join('\n')}
};
static const AstroWallData ASTRO_WALL_DATA[${walls.length}]={
${walls.join('\n')}
};
static const AstroPartData ASTRO_PART_DATA[${Math.max(1,parts.length)}]={
${parts.join('\n')||' {"",0,{1,0,0,1,0,0},1},'}
};
static const double ASTRO_TURRET_BOXES[${Math.max(1,turretBoxes.length)}][4]={
${turretBoxes.join('\n')||' {0,0,0,0},'}
};
static const AstroObjectData ASTRO_OBJECT_DATA[ASTRO_OBJECTS]={
${objects.join('\n')}
};
static const AstroLevelData ASTRO_LEVEL_DATA[ASTRO_LEVELS]={
${levels.join('\n')}
};
static const AstroIntroData ASTRO_INTRO_DATA[ASTRO_INTROS]={
${intros.join('\n')}
};
`;
await writeFile(path.join(root,'source/game_astro_data.h'),out);
console.log(`Wrote ${objects.length} objects, ${clips.length} clips (${frames.length} frames), ${walls.length} walls, ${intros.length} intros`);
