// Generates source/furniture_sort_data.h from the web furniture catalogue.
// Usage: node tools/import-furniture-sort.mjs path/to/furniture.json
//
// The 3DS client data rows carry the placement type only. The editor groups
// furniture by catalogue section (sort), the same field the web editor uses.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const input = process.argv[2];
if (!input) {
  console.error('Usage: node tools/import-furniture-sort.mjs path/to/furniture.json');
  process.exit(2);
}

const rows = JSON.parse(await readFile(input, 'utf8'));
const furniture = rows
  .filter(row => Number.isInteger(row.id) && row.id > 0 && row.id <= 0xffff)
  .filter(row => Number.isInteger(row.sort) && row.sort >= 1 && row.sort <= 4)
  .sort((a, b) => a.id - b.id);

if (furniture.length === 0) {
  console.error('No furniture with a catalogue section was found.');
  process.exit(1);
}

const body = furniture
  .map(row => ` {${row.id},${row.sort}}`)
  .reduce((lines, entry, index) => {
    const line = Math.floor(index / 12);
    lines[line] = (lines[line] ?? '') + entry + ',';
    return lines;
  }, [])
  .join('\n');

const header = `/* Generated by tools/import-furniture-sort.mjs. Do not edit by hand.
 * ${furniture.length} furniture items from the web catalogue.
 * Catalogue sections: 1 room, 2 wall, 3 floor, 4 puffle. */
#pragma once
#define FURNITURE_SORT_COUNT ${furniture.length}
static const unsigned short furnitureSort[FURNITURE_SORT_COUNT][2]={
${body}
};
`;

const output = path.resolve(import.meta.dirname, '../source/furniture_sort_data.h');
await writeFile(output, header);
console.log(`PASS furniture sections: ${furniture.length} items -> ${path.relative(process.cwd(), output)}`);
